import path from "path";

jest.mock("fs", () => ({
  promises: {
    readdir: jest.fn(),
    readFile: jest.fn(),
    access: jest.fn(),
    stat: jest.fn(),
  },
}));

import { promises as fsMock } from "fs";
import { readPlaylists } from "./playlists";

const mockReaddir = fsMock.readdir as jest.Mock;
const mockReadFile = fsMock.readFile as jest.Mock;
const mockAccess = fsMock.access as jest.Mock;
const mockStat = fsMock.stat as jest.Mock;

const LIBRARY = "/library";
const PLAYLIST_PATH = path.join(LIBRARY, "Favorites.m3u8");
const TRACK_PATH =
  "/library/Queen/A Night at the Opera [1975]/11 - Bohemian Rhapsody.flac";

const M3U8_CONTENT = [
  "#EXTM3U",
  "#EXTINF:354,Queen - Bohemian Rhapsody",
  TRACK_PATH,
].join("\n");

const BIRTH = new Date("2024-01-01T00:00:00.000Z");

beforeEach(() => {
  jest.clearAllMocks();
  mockStat.mockResolvedValue({ birthtime: BIRTH, size: 100 });
  mockAccess.mockResolvedValue(undefined);
});

describe("readPlaylists — basic reading (MFM-412)", () => {
  it("returns empty array when library folder is empty", async () => {
    mockReaddir.mockResolvedValue([]);
    expect(await readPlaylists(LIBRARY)).toEqual([]);
  });

  it("returns empty array when readdir fails", async () => {
    mockReaddir.mockRejectedValue(new Error("ENOENT"));
    expect(await readPlaylists(LIBRARY)).toEqual([]);
  });

  it("ignores non-.m3u8 files", async () => {
    mockReaddir.mockResolvedValue(["cover.jpg", "notes.txt"]);
    expect(await readPlaylists(LIBRARY)).toEqual([]);
  });

  it("returns one playlist for one .m3u8 file", async () => {
    mockReaddir.mockResolvedValue(["Favorites.m3u8"]);
    mockReadFile.mockResolvedValue(M3U8_CONTENT);

    const result = await readPlaylists(LIBRARY);
    expect(result).toHaveLength(1);
    expect(result[0].name).toBe("Favorites");
    expect(result[0].filePath).toBe(PLAYLIST_PATH);
  });

  it("sets createdAt from file stat birthtime", async () => {
    mockReaddir.mockResolvedValue(["Favorites.m3u8"]);
    mockReadFile.mockResolvedValue(M3U8_CONTENT);

    const [playlist] = await readPlaylists(LIBRARY);
    expect(playlist.createdAt).toBe(BIRTH.toISOString());
  });

  it("sets autoGenerated to false", async () => {
    mockReaddir.mockResolvedValue(["Favorites.m3u8"]);
    mockReadFile.mockResolvedValue(M3U8_CONTENT);

    const [playlist] = await readPlaylists(LIBRARY);
    expect(playlist.autoGenerated).toBe(false);
  });
});

describe("readPlaylists — entry parsing (MFM-412)", () => {
  it("parses artist and title from EXTINF line", async () => {
    mockReaddir.mockResolvedValue(["Favorites.m3u8"]);
    mockReadFile.mockResolvedValue(M3U8_CONTENT);

    const [playlist] = await readPlaylists(LIBRARY);
    expect(playlist.entries[0].artist).toBe("Queen");
    expect(playlist.entries[0].title).toBe("Bohemian Rhapsody");
  });

  it("sets filePath on each entry", async () => {
    mockReaddir.mockResolvedValue(["Favorites.m3u8"]);
    mockReadFile.mockResolvedValue(M3U8_CONTENT);

    const [playlist] = await readPlaylists(LIBRARY);
    expect(playlist.entries[0].filePath).toBe(TRACK_PATH);
  });

  it("sets status 'ok' when file exists", async () => {
    mockReaddir.mockResolvedValue(["Favorites.m3u8"]);
    mockReadFile.mockResolvedValue(M3U8_CONTENT);
    mockAccess.mockResolvedValue(undefined);

    const [playlist] = await readPlaylists(LIBRARY);
    expect(playlist.entries[0].status).toBe("ok");
  });
});

describe("readPlaylists — orphan detection (MFM-412)", () => {
  it("marks entry as 'orphaned' when file does not exist", async () => {
    mockReaddir.mockResolvedValue(["Favorites.m3u8"]);
    mockReadFile.mockResolvedValue(M3U8_CONTENT);
    mockAccess.mockRejectedValue(new Error("ENOENT"));

    const [playlist] = await readPlaylists(LIBRARY);
    expect(playlist.entries[0].status).toBe("orphaned");
  });

  it("marks only missing files as orphaned when playlist has mixed entries", async () => {
    const existing = "/library/exists.flac";
    const missing = "/library/gone.flac";
    const content = [
      "#EXTM3U",
      "#EXTINF:120,A - Exists",
      existing,
      "#EXTINF:120,B - Gone",
      missing,
    ].join("\n");

    mockReaddir.mockResolvedValue(["Mix.m3u8"]);
    mockReadFile.mockResolvedValue(content);
    mockAccess.mockImplementation((p: string) =>
      p === existing ? Promise.resolve() : Promise.reject(new Error("ENOENT")),
    );

    const [playlist] = await readPlaylists(LIBRARY);
    expect(playlist.entries[0].status).toBe("ok");
    expect(playlist.entries[1].status).toBe("orphaned");
  });
});
