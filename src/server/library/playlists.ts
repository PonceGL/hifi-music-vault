import { createHash } from "crypto";
import { promises as fs } from "fs";
import path from "path";
import type { Playlist, PlaylistEntry } from "@/types/playlist";

function trackIdFromPath(absolutePath: string): string {
  return createHash("sha256").update(absolutePath).digest("hex").slice(0, 32);
}

interface ExtinfData {
  title: string | null;
  artist: string | null;
}

function parseExtinf(line: string): ExtinfData {
  const match = /^#EXTINF:-?\d+,(.+)$/.exec(line);
  if (!match) return { title: null, artist: null };

  const display = match[1].trim();
  const sep = display.indexOf(" - ");
  if (sep !== -1) {
    return {
      artist: display.slice(0, sep).trim() || null,
      title: display.slice(sep + 3).trim() || null,
    };
  }
  return { title: display || null, artist: null };
}

async function parseM3u8(
  playlistPath: string,
): Promise<Omit<PlaylistEntry, "trackId">[]> {
  const content = await fs.readFile(playlistPath, "utf-8");
  const lines = content.split(/\r?\n/).map((l) => l.trim());
  const entries: Omit<PlaylistEntry, "trackId">[] = [];
  const dir = path.dirname(playlistPath);

  let pending: ExtinfData | null = null;

  for (const line of lines) {
    if (!line || line === "#EXTM3U") continue;

    if (line.startsWith("#EXTINF:")) {
      pending = parseExtinf(line);
      continue;
    }

    if (line.startsWith("#")) continue;

    const filePath = path.isAbsolute(line) ? line : path.resolve(dir, line);

    let status: "ok" | "orphaned" = "ok";
    try {
      await fs.access(filePath);
    } catch {
      status = "orphaned";
    }

    entries.push({
      filePath,
      title: pending?.title ?? null,
      artist: pending?.artist ?? null,
      status,
    });

    pending = null;
  }

  return entries;
}

export async function readPlaylists(libraryPath: string): Promise<Playlist[]> {
  let entries: string[];
  try {
    entries = await fs.readdir(libraryPath);
  } catch {
    return [];
  }

  const m3u8Files = entries.filter((f) => f.endsWith(".m3u8"));

  const playlists = await Promise.all(
    m3u8Files.map(async (file): Promise<Playlist> => {
      const filePath = path.join(libraryPath, file);
      const name = path.basename(file, ".m3u8");
      const rawEntries = await parseM3u8(filePath);

      const stat = await fs.stat(filePath).catch(() => null);

      return {
        id: trackIdFromPath(filePath),
        name,
        filePath,
        entries: rawEntries.map((e) => ({
          ...e,
          trackId: trackIdFromPath(e.filePath),
        })),
        createdAt: stat?.birthtime.toISOString() ?? new Date(0).toISOString(),
        autoGenerated: false,
      };
    }),
  );

  return playlists;
}
